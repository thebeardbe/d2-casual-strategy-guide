import { writeFileSync } from 'node:fs'
import { availableActs, areasInOrder } from '../src/data/acts'
import { areaMapTypeLabel } from '../src/data/mapTypes'

function time(seconds: number) {
  return `${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, '0')}`
}

const join = (items: string[]) => (items.length ? items.join('; ') : 'not listed')

const HEADER = (roman: string) => `# Act ${roman} checklist

Generated by \`tools/checklist.ts\`. Compare each row against the video link.
"Picture" says whether the card shows a layout screenshot: only fixed, fixed
enough and alternating fixed maps do, because a rendered example of a variable map
would be one random arrangement. "alvl" is normal / nightmare / hell, and L85 marks
the top farming tier.

| Area | Type | Features | Entrance | Exit | Waypoint | alvl | Picture | Video |
|---|---|---|---|---|---|---|---|---|
`

for (const act of availableActs) {
  let out = HEADER(act.roman)
  for (const area of areasInOrder(act)) {
    const levels = (area.areaLevels ?? [])
      .map((entry) => `${entry.label ? `${entry.label} ` : ''}${entry.normal}/${entry.nightmare}/${entry.hell}`)
      .join('; ')
    const top = (area.areaLevels ?? []).some((entry) => entry.hell >= 85) ? ' L85' : ''
    const farming = (area.farming ?? []).map((entry) => entry.topic).join('; ')
    const cells = [
      area.name,
      areaMapTypeLabel(area),
      join(area.features),
      join(area.entrance),
      join(area.exit),
      area.waypoint ? area.waypoint.where : 'none',
      `${levels || 'none'}${top}`,
      area.example ? 'yes' : 'no',
      time(area.videoTime),
    ]
    out += `| ${cells.join(' | ')} |${farming ? ` farming: ${farming}` : ''}\n`
  }
  const path = `docs/act${act.number}-checklist.md`
  writeFileSync(path, out)
  console.log(path)
}
