import { availableActs, areasInOrder } from '../src/data/acts'
import { areaMapTypeLabel } from '../src/data/mapTypes'

function time(seconds: number) {
  return `${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, '0')}`
}
const join = (items: string[]) => (items.length ? items.join('; ') : 'not listed')

let out = `# Act I checklist\n\nGenerated by tools/checklist.ts; compare each row against the video link. "Picture"\nsays whether the card shows a layout screenshot: only fixed, fixed enough and\nalternating fixed maps do, because a rendered example of a variable map would be\none random arrangement. "alvl" is normal / nightmare / hell, and L85 marks the\ntop farming tier.\n\n| Area | Type | Features | Entrance | Exit | Waypoint | alvl | Picture | Video |\n|---|---|---|---|---|---|---|---|---|\n`
for (const act of availableActs) {
  for (const area of areasInOrder(act)) {
    const levels = (area.areaLevels ?? [])
      .map((entry) => `${entry.label ? `${entry.label} ` : ''}${entry.normal}/${entry.nightmare}/${entry.hell}`)
      .join('; ')
    const top = (area.areaLevels ?? []).some((entry) => entry.hell >= 85) ? ' L85' : ''
    const farming = (area.farming ?? []).map((entry) => entry.topic).join('; ')
    out += `| ${area.name} | ${areaMapTypeLabel(area)} | ${join(area.features)} | ${join(area.entrance)} | ${join(area.exit)} | ${area.waypoint ? area.waypoint.where : 'none'} | ${levels || 'none'}${top} | ${area.example ? 'yes' : 'no'} | ${time(area.videoTime)} |${farming ? ` farming: ${farming}` : ''}\n`
  }
}
console.log(out)
